"""Durable ingestion activity and diagnostics.

Every ingestion attempt -- successful, blocked, or failed -- produces
an ordered, structured event trace generated by the actual backend
execution (never inferred from HTTP status by the UI).  Traces are
persisted as JSON beside the evaluation store (a sibling
``ingestion-activity`` directory), entirely separate from authoritative
evaluation artifacts: a failed ingestion has a durable diagnostic
record without having produced a valid evaluation, and those two facts
remain separate.

Event contract (version 1): each event carries ``ingestion_id``,
``correlation_id``, ``sequence`` (deterministic order), ``timestamp``,
``stage``, ``event_type``, ``status``, ``message`` and, where
applicable, ``details`` (sanitized, bounded), ``duration_ms``,
``source_reference``, ``error_code`` and ``retryable``.

Safety: details are sanitized before persistence -- keys that could
carry credentials/cookies/tokens are dropped, strings are truncated,
and nesting/collections are bounded. No full uploaded documents or raw source
response bodies are recorded. Selected issue-field evidence quotations may be
retained as bounded, numbered parts for lossless diagnostic readback; they do
not constitute evaluation artifacts or upgrade a candidate's verification.
"""

from __future__ import annotations

import json
import re
import threading
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

EVENT_CONTRACT_VERSION = 1

STAGE_STATUSES = (
    "PENDING",
    "RUNNING",
    "SUCCEEDED",
    "FAILED",
    "BLOCKED",
    "SKIPPED",
    "CANCELLED",
)

TERMINAL_STATUSES = ("SUCCEEDED", "FAILED", "BLOCKED", "CANCELLED")

_MAX_STRING = 600
_MAX_DEPTH = 3
_MAX_ITEMS = 20
_SENSITIVE_KEY = re.compile(r"cookie|token|authorization|password|secret|api[-_]?key", re.IGNORECASE)


def _utcnow_iso() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def sanitize_details(value: Any, _depth: int = 0) -> Any:
    """Bound and redact diagnostic details before persistence/display."""
    if _depth > _MAX_DEPTH:
        return "…"
    if isinstance(value, dict):
        out: Dict[str, Any] = {}
        for key, item in list(value.items())[:_MAX_ITEMS]:
            key_str = str(key)
            if _SENSITIVE_KEY.search(key_str):
                out[key_str] = "[redacted]"
            else:
                out[key_str] = sanitize_details(item, _depth + 1)
        return out
    if isinstance(value, (list, tuple)):
        return [sanitize_details(item, _depth + 1) for item in list(value)[:_MAX_ITEMS]]
    if isinstance(value, str):
        return value if len(value) <= _MAX_STRING else value[:_MAX_STRING] + "…"
    if isinstance(value, (int, float, bool)) or value is None:
        return value
    return str(value)[:_MAX_STRING]


class IngestionActivityStore:
    """Filesystem store for ingestion activity traces.

    One JSON file per ingestion attempt, written atomically (temp file
    + replace) so a reader never observes a partial trace.  Retention
    is explicit and bounded: at most ``max_records`` traces are kept,
    oldest first out.  This is a diagnostic store only; it is never
    consulted for evaluation results.
    """

    def __init__(self, root: str | Path, max_records: int = 200) -> None:
        self.root = Path(root)
        self.max_records = max_records
        # NTFS replacement can deny concurrent opens of the destination.
        # Atomic publication does not by itself synchronize Windows readers.
        self._io_lock = threading.RLock()

    def _path(self, ingestion_id: str) -> Path:
        safe = re.sub(r"[^A-Za-z0-9_-]", "", str(ingestion_id))[:64]
        return self.root / f"{safe}.json"

    def new_recorder(self, *, filename: str, mode: str) -> "IngestionRecorder":
        ingestion_id = f"ing-{uuid.uuid4().hex[:16]}"
        recorder = IngestionRecorder(self, ingestion_id, filename=filename, mode=mode)
        recorder.emit(
            "upload",
            "received",
            "RUNNING",
            "Upload received; ingestion started.",
            details={"filename": filename, "mode": mode},
        )
        self._prune()
        return recorder

    def save(self, record: Dict[str, Any]) -> None:
        with self._io_lock:
            self.root.mkdir(parents=True, exist_ok=True)
            path = self._path(str(record["ingestion_id"]))
            tmp = path.with_suffix(".tmp")
            tmp.write_text(json.dumps(record, indent=2, sort_keys=False), encoding="utf-8")
            tmp.replace(path)  # atomic on POSIX and Windows

    def get(self, ingestion_id: str) -> Optional[Dict[str, Any]]:
        with self._io_lock:
            path = self._path(ingestion_id)
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except FileNotFoundError:
                return None  # I/O errors and corrupt records are not absence

    def list_recent(self, limit: int = 50) -> List[Dict[str, Any]]:
        with self._io_lock:
            if not self.root.is_dir():
                return []
            files = sorted(
                (p for p in self.root.glob("*.json") if p.is_file()),
                key=lambda p: p.stat().st_mtime,
                reverse=True,
            )
            out: List[Dict[str, Any]] = []
            for path in files[: max(1, min(limit, 200))]:
                try:
                    record = json.loads(path.read_text(encoding="utf-8"))
                except Exception:
                    continue
                out.append({k: v for k, v in record.items() if k != "events"})
            return out

    def _prune(self) -> None:
        with self._io_lock:
            try:
                if not self.root.is_dir():
                    return
                files = sorted(
                    (p for p in self.root.glob("*.json") if p.is_file()),
                    key=lambda p: p.stat().st_mtime,
                )
                for path in files[: max(0, len(files) - self.max_records)]:
                    try:
                        path.unlink()
                    except OSError:
                        pass
            except Exception:
                pass  # retention is best-effort; never fails an ingestion


class IngestionRecorder:
    """Thread-safe event recorder for one ingestion attempt."""

    def __init__(
        self,
        store: IngestionActivityStore,
        ingestion_id: str,
        *,
        filename: str,
        mode: str,
    ) -> None:
        self._store = store
        self._lock = threading.Lock()
        self.record: Dict[str, Any] = {
            "contract_version": EVENT_CONTRACT_VERSION,
            "ingestion_id": ingestion_id,
            "correlation_id": ingestion_id,
            "filename": filename,
            "mode": mode,
            "status": "RUNNING",
            "started_at": _utcnow_iso(),
            "finished_at": None,
            "evaluation_id": None,
            "evaluation_run": False,
            "persisted": False,
            "is_duplicate": False,
            "error_code": None,
            "error_message": None,
            "missing_fields": [],
            "result": None,
            "events": [],
        }
        self._started = time.monotonic()
        self._stage_starts: Dict[str, float] = {}

    @property
    def ingestion_id(self) -> str:
        return str(self.record["ingestion_id"])

    def emit(
        self,
        stage: str,
        event_type: str,
        status: str,
        message: str,
        *,
        details: Optional[Dict[str, Any]] = None,
        source_reference: Optional[str] = None,
        error_code: Optional[str] = None,
        retryable: Optional[bool] = None,
        duration_ms: Optional[float] = None,
    ) -> Dict[str, Any]:
        if status not in STAGE_STATUSES:
            status = "FAILED" if status == "ERROR" else "RUNNING"
        with self._lock:
            if status == "RUNNING":
                self._stage_starts[stage] = time.monotonic()
            elif duration_ms is None and stage in self._stage_starts:
                duration_ms = round((time.monotonic() - self._stage_starts.pop(stage)) * 1000, 1)
            event = {
                "ingestion_id": self.ingestion_id,
                "correlation_id": self.ingestion_id,
                "sequence": len(self.record["events"]) + 1,
                "timestamp": _utcnow_iso(),
                "stage": stage,
                "event_type": event_type,
                "status": status,
                "message": str(message)[:_MAX_STRING],
                "details": sanitize_details(details) if details else {},
                "duration_ms": duration_ms,
                "source_reference": (str(source_reference)[:_MAX_STRING] if source_reference else None),
                "error_code": error_code,
                "retryable": retryable,
            }
            self.record["events"].append(event)
            self._store.save(self.record)
            return event

    def finish(
        self,
        status: str,
        *,
        error_code: Optional[str] = None,
        error_message: Optional[str] = None,
        missing_fields: Optional[List[str]] = None,
    ) -> None:
        """Set the unambiguous terminal outcome and persist it."""
        if status not in TERMINAL_STATUSES:
            status = "FAILED"
        with self._lock:
            self.record["status"] = status
            self.record["finished_at"] = _utcnow_iso()
            self.record["error_code"] = error_code
            self.record["error_message"] = (
                str(error_message)[:_MAX_STRING] if error_message else None
            )
            if missing_fields is not None:
                self.record["missing_fields"] = [str(f) for f in missing_fields]
        self.emit(
            "finalization",
            "completed" if status == "SUCCEEDED" else "terminated",
            status,
            (
                f"Ingestion {status.lower()}: "
                + (
                    "evaluation persisted."
                    if status == "SUCCEEDED" and self.record.get("persisted")
                    else "existing evaluation returned (duplicate)."
                    if status == "SUCCEEDED"
                    else (error_message or "see stage events for the failure stage and reason.")
                )
            ),
            details={
                "evaluation_run": bool(self.record.get("evaluation_run")),
                "persisted": bool(self.record.get("persisted")),
                "evaluation_id": self.record.get("evaluation_id"),
                "missing_fields": self.record.get("missing_fields") or [],
                "duration_ms": round((time.monotonic() - self._started) * 1000, 1),
            },
            error_code=error_code,
            retryable=(status == "FAILED" and error_code in ("INGESTION_INTERNAL_ERROR",)),
        )

    def snapshot(self) -> Dict[str, Any]:
        with self._lock:
            return json.loads(json.dumps(self.record))
